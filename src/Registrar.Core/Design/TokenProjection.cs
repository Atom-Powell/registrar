using System.Text;
using System.Text.RegularExpressions;
using Registrar.Core.Config;

namespace Registrar.Core.Design;

// Derives the operator GUI's color tokens from the same config the renderer uses, so
// the application and the documents it produces cannot drift onto different palettes.
//
// Names are derived rather than mapped. A lookup table would fall out of step with
// config the first time someone added a color, and the drift would be invisible until
// somebody put a screen beside a deliverable.
public static class TokenProjection
{
    // The two blocks are emitted as labelled groups rather than one alphabetical run.
    // Sorted together, --org-border (3.47:1 on white, the safe one) and
    // --org-border-neutral (1.82:1, the reason the screen block exists) land on
    // consecutive lines under equally official names, and nothing in the file tells a
    // consumer which one a control boundary wants. Grouping puts that guidance where it
    // is read. The ordinal sort is kept inside each group so output stays deterministic.
    public static string Render(ConfigBundle config, string styleRulesSha256)
    {
        var claimed = new HashSet<string>(StringComparer.Ordinal);
        var document = Collect(claimed, config.Style.Colors, "visualIdentity.colors");
        var screen = Collect(claimed, config.Screen.Colors, "screen.colors");

        var sb = new StringBuilder();
        sb.Append("/* Generated by registrar emit-tokens. Do not edit by hand: edits are\n");
        sb.Append("   overwritten on the next run, and a committed copy that disagrees with\n");
        sb.Append("   config fails the build.\n");
        sb.Append("\n");
        sb.Append("   Source: config/style-rules.json\n");
        sb.Append("   SHA-256: ").Append(styleRulesSha256).Append("\n");
        sb.Append("\n");
        sb.Append("   The tokens below are in two groups. Read the group comment before\n");
        sb.Append("   picking one: the groups are not interchangeable. */\n");
        sb.Append(":root {\n");

        sb.Append("  /* Screen tokens. These are the tokens chosen for interactive UI.\n");
        sb.Append("     Use these for on-screen text, controls, and control boundaries.\n");
        sb.Append("     Each one is measured against its role by the engine's contrast\n");
        sb.Append("     tests. Source: screen.colors in config/style-rules.json. */\n");
        Emit(sb, screen);

        sb.Append("\n");
        sb.Append("  /* Document tokens. This is the document palette, shared with the\n");
        sb.Append("     DOCX renderer, and it is not screen-safe as a set: some of these\n");
        sb.Append("     fail WCAG as interactive foreground, because they were chosen for\n");
        sb.Append("     print. Do not assume a document color is screen-safe: several of\n");
        sb.Append("     these were chosen for print, not screen. For a control boundary,\n");
        sb.Append("     use the screen group above. For text, four of these are validated\n");
        sb.Append("     as text on white by the engine's own contrast tests, namely --org-primary-blue, --org-heading-navy, --org-accent-blue, and --org-secondary-gray.\n");
        sb.Append("     They are exported so the application can match the deliverables it\n");
        sb.Append("     produces, for example when previewing a document or tinting a\n");
        sb.Append("     surface.\n");
        sb.Append("     Source: visualIdentity.colors in config/style-rules.json. */\n");
        Emit(sb, document);

        sb.Append("}\n");
        return sb.ToString();
    }

    private static void Emit(StringBuilder sb, IEnumerable<KeyValuePair<string, string>> tokens)
    {
        foreach (var (name, value) in tokens.OrderBy(t => t.Key, StringComparer.Ordinal))
            sb.Append("  ").Append(name).Append(": ").Append(value).Append(";\n");
    }

    // Requires at least one lowercase/digit character after every capital, which is
    // what actually forbids two capitals in a row: "^[a-z][a-z0-9]*([A-Z][a-z0-9]*)*$"
    // looks equivalent but is not, because its trailing "*" lets a capital be followed
    // by zero lowercase characters, so "brandURLColor" satisfies it one letter at a
    // time. The "+" below closes that gap.
    private static readonly Regex LowerCamelCase = new(
        "^[a-z0-9]+(?:[A-Z][a-z0-9]+)*$", RegexOptions.Compiled);

    // camelCase to kebab-case, prefixed. Derived so a new config color appears in the
    // stylesheet automatically and no table can fall out of step.
    //
    // The shape is validated first rather than guessed through. A leading capital or a
    // run of consecutive capitals is ambiguous: the derivation cannot tell whether
    // consecutive capitals mark an acronym (which might want to stay grouped) or two
    // separate words (which would each want their own hyphen), and guessing would
    // produce a name nobody intended. Rejecting the key is the same fail-closed choice
    // the collision guard below makes: a name we cannot stand behind is not emitted.
    public static string TokenName(string configKey)
    {
        if (!LowerCamelCase.IsMatch(configKey))
        {
            throw new InvalidOperationException(
                $"Config key \"{configKey}\" is not lowerCamelCase; a token name cannot be "
                + "derived from it. Color keys must start with a lowercase letter and must "
                + "not contain consecutive uppercase letters.");
        }

        var sb = new StringBuilder("--org-");

        foreach (var ch in configKey)
        {
            if (char.IsUpper(ch))
            {
                sb.Append('-').Append(char.ToLowerInvariant(ch));
            }
            else
            {
                sb.Append(ch);
            }
        }

        return sb.ToString();
    }

    // Fails closed on a collision rather than letting the second write win. The groups
    // are presentational only: both blocks still feed one flat custom-property namespace,
    // so a duplicate would be a palette change nobody decided, and the shared "claimed"
    // set is what keeps the check whole-file rather than per-group.
    private static Dictionary<string, string> Collect(
        HashSet<string> claimed,
        IReadOnlyDictionary<string, string> colors,
        string source)
    {
        var tokens = new Dictionary<string, string>(StringComparer.Ordinal);

        foreach (var (key, value) in colors)
        {
            var name = TokenName(key);

            if (!claimed.Add(name))
            {
                throw new InvalidOperationException(
                    $"Token {name} is claimed by more than one config block; {source} would "
                    + "overwrite an earlier definition. Rename one of the color keys.");
            }

            tokens[name] = value;
        }

        return tokens;
    }
}
